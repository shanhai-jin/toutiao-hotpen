# -*- coding: utf-8 -*-
"""hotpen_cn_rules.py — 汉字数字使用规则检测（头条热笔原创实现）

规则思想：头条图文正文中的数量表达一律使用阿拉伯数字，
"汉字数词+量词/时间词"组合是审核与机审的高风险特征。
本模块只做"模式识别"，返回命中列表；是否 FAIL 由上层脚本决定。

本文件为「头条热笔」项目原创代码，基于公开的平台创作规范思路独立实现。
"""

import re

# 量词表：常见实物/抽象计量单位（可按需增删）
_UNITS = (
    "台件条张只家款间套名批轮场遍顿句盒辆匹头棵颗座层栋枚篇支枝宗道列"
    "期班波桶罐瓶壶碟盘碗锅勺帧格档项部章节日单笔份本册页幅堵扇"
)
_UNITS_RE = "[" + _UNITS + "]"

# 汉字数词（含"两"，阿拉伯场景下"两"必须转写）
_NUM = "零一二两三四五六七八九十百千"

# 命中模式：
#   1) 汉字数词 + 量词          例：一台 / 三张 / 那两台
#   2) 汉字数词 + 万 + 量词      例：4 万台 的汉字写法
#   3) 两 + 时间词              例：两年 / 两天 / 两小时
#   4) 俩 + 量词                例：俩人（口语残留）
_PATTERNS = [
    re.compile("[" + _NUM + "]+(?:" + _UNITS_RE + ")"),
    re.compile("[" + _NUM + "]+万(?:" + _UNITS_RE + ")"),
    re.compile("两(?:年|天|月|小时|半小时|周|次|回|遍|句|步|夜|季度|分钟|秒)"),
    re.compile("俩" + _UNITS_RE),
]

# 豁免白名单：汉语固定搭配与叙事惯用语，不是需要转写的数量表达
_ALLOW = {
    "一个", "两个", "一场", "一条", "一片", "一声", "一张", "零头",
    "第一批", "统一", "唯一", "一起", "一直", "一样", "一边", "一切",
    "万一", "单一", "一体", "一味", "一线", "一路", "一旦", "第一位",
}


def scan(text):
    """扫描文本中的汉字数字，返回 [(命中片段, 前后文), ...]"""
    found = [(m.group(0), m.start(), m.end())
             for pat in _PATTERNS for m in pat.finditer(text)]
    return [(w, text[max(0, s - 6):min(len(text), e + 6)].replace("\n", " "))
            for w, s, e in found if w not in _ALLOW]


if __name__ == "__main__":
    demo = "小区里有一台旧打印机，用了两年。他家两个孩子的成绩一样好，一共三张奖状。"
    for w, c in scan(demo):
        print("命中:", w, "| 上下文:", c)
